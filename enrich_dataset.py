def brandify(allopathic: str) -> str:
    """Append common brand names to each generic medicine line."""
    if not allopathic:
        return allopathic
    out = []
    for med in allopathic.split(";"):
        med = med.strip()
        if not med:
            continue
        generic = med.split("(")[0].strip().lower()
        added = False
        for key, brands in BRANDS.items():
            if key in generic:
                out.append(f"{med} [brands: {', '.join(brands)}]")
                added = True
                break
        if not added:
            out.append(med)
    return "; ".join(out)


def categorize(department: str) -> str:
    dep = (department or "").lower()
    rules = [
        ("cardio", "cardiac"), ("cardiolog", "cardiac"), ("internal medicine", "cardiac"),
        ("gastro", "gut"), ("hepato", "gut"), ("proctolog", "gut"), ("colorectal", "gut"),
        ("neuro", "neuro"), ("psychiat", "mental"), ("psycholog", "mental"),
        ("dermatolog", "skin"), ("allerg", "skin"),
        ("pulmonolog", "resp"), ("chest", "resp"),
        ("ent", "ent_eye"), ("ophthalmolog", "ent_eye"),
        ("endocrinolog", "endo"), ("diabetolog", "endo"),
        ("nephrolog", "renal"), ("urolog", "renal"),
        ("rheumatolog", "bone"), ("orthopedic", "bone"), ("physiotherapist", "bone"), ("sports", "bone"),
        ("dentist", "dental"), ("maxillofacial", "dental"),
        ("gynaecolog", "gyn"),
        ("emergency", "emergency"),
    ]
    for needle, cat in rules:
        if needle in dep:
            return cat
    return "general"


